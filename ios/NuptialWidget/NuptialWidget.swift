//  Sizes. Android lets you resize one widget between a 1-cell glyph+word and
//  a wider cell with the odds as well. iOS cannot do that: a placed widget
//  has a fixed family, and there is no 1x1 home-screen family at all -
//  .systemSmall already occupies a 2x2 block of icons and is the floor Apple
//  offers. So the nearest equivalent is to publish several families and let
//  you pick when adding: .systemSmall mirrors the compact Android layout,
//  .systemMedium mirrors the wider one, and the Lock Screen accessories
//  (iOS 16+) are the genuinely small option.
//
