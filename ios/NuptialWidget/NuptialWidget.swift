private func glyphImage(winged: Bool) -> UIImage? {
    let b64 = winged ? queenGlyphBase64 : workerGlyphBase64
    guard let data = Data(base64Encoded: b64), let image = UIImage(data: data) else {
        return nil
    }
    return image.withRenderingMode(.alwaysTemplate)
}

// MARK: - View

struct NuptialWidgetEntryView: View {
    @Environment(\.widgetFamily) private var family
    var entry: FlightEntry

    private var band: Band? { bands[entry.bandKey] }

    private var label: String {
        if !entry.label.isEmpty { return entry.label }
        return band?.fallbackLabel ?? "..."
    }

    private var foreground: Color {
        guard let band = band else { return dynamic(textPrimary.0, textPrimary.1) }
        return dynamic(band.fgLight, band.fgDark)
    }

    private var background: Color {
        guard let band = band else { return dynamic(neutralBg.0, neutralBg.1) }
        return dynamic(band.bgLight, band.bgDark)
    }

    private var secondary: Color { dynamic(textSecondary.0, textSecondary.1) }

    /// Long localized band words (e.g. "Vielversprechend") need a smaller
    /// size to stay on one line, as on Android.
    private func labelSize(_ base: CGFloat) -> CGFloat {
        if label.count > 12 { return base * 0.68 }
        if label.count > 9 { return base * 0.82 }
        return base
    }

    private func glyph(width: CGFloat, color: Color) -> some View {
        Group {
            if let image = glyphImage(winged: band?.winged == true) {
                Image(uiImage: image)
                    .resizable()
                    .aspectRatio(contentMode: .fit)
                    .frame(width: width)
                    .foregroundColor(color)
            }
        }
        .accessibilityHidden(true)
    }

    // Compact: mirrors the 1-cell Android layout (glyph + band word + odds).
    private var smallBody: some View {
        VStack(spacing: 3) {
            glyph(width: 42, color: secondary)
            Text(label)
                .font(.system(size: labelSize(22), weight: .semibold))
                .minimumScaleFactor(0.7)
                .lineLimit(1)
                .foregroundColor(foreground)
            if !entry.odds.isEmpty {
                Text(entry.odds)
                    .font(.system(size: 12))
                    .lineLimit(1)
                    .foregroundColor(secondary)
            }
        }
        .padding(6)
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }

    // Wide: mirrors the fuller Android layout, heading included.
    private var mediumBody: some View {
        HStack(spacing: 14) {
            glyph(width: 74, color: secondary)
            VStack(alignment: .leading, spacing: 2) {
                Text("ANT FLIGHTS")
                    .font(.system(size: 11))
                    .kerning(1.2)
                    .foregroundColor(secondary)
                Text(label)
                    .font(.system(size: labelSize(30), weight: .semibold))
                    .minimumScaleFactor(0.6)
                    .lineLimit(1)
                    .foregroundColor(foreground)
                if !entry.odds.isEmpty {
                    Text(entry.odds)
                        .font(.system(size: 14))
                        .lineLimit(1)
                        .foregroundColor(secondary)
                }
            }
            Spacer(minLength: 0)
        }
        .padding(.horizontal, 16)
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }

    // Lock Screen. These are rendered as a system tint, so no band colour.
    @available(iOSApplicationExtension 16.0, *)
    private var circularBody: some View {
        ZStack {
            AccessoryWidgetBackground()
            VStack(spacing: 0) {
                glyph(width: 26, color: .primary)
                if !entry.odds.isEmpty {
                    Text(entry.odds)
                        .font(.system(size: 10, weight: .semibold))
                        .minimumScaleFactor(0.6)
                        .lineLimit(1)
                }
            }
            .padding(4)
        }
    }

    @available(iOSApplicationExtension 16.0, *)
    private var rectangularBody: some View {
        HStack(spacing: 7) {
            glyph(width: 30, color: .primary)
            VStack(alignment: .leading, spacing: 1) {
                Text(label)
                    .font(.system(size: 15, weight: .semibold))
                    .lineLimit(1)
                    .minimumScaleFactor(0.7)
                if !entry.odds.isEmpty {
                    Text(entry.odds)
                        .font(.system(size: 12))
                        .lineLimit(1)
                }
            }
            Spacer(minLength: 0)
        }
    }

    private var inlineText: String {
        entry.odds.isEmpty ? label : label + " - " + entry.odds
    }

    @ViewBuilder
    private var content: some View {
        if #available(iOSApplicationExtension 16.0, *), family == .accessoryCircular {
            circularBody.widgetBackgroundCompat(Color.clear)
        } else if #available(iOSApplicationExtension 16.0, *), family == .accessoryRectangular {
            rectangularBody.widgetBackgroundCompat(Color.clear)
        } else if #available(iOSApplicationExtension 16.0, *), family == .accessoryInline {
            Text(inlineText).widgetBackgroundCompat(Color.clear)
        } else if family == .systemMedium {
            mediumBody.widgetBackgroundCompat(background)
        } else {
            smallBody.widgetBackgroundCompat(background)
        }
    }

    var body: some View {
        content.accessibilityLabel(accessibilityText)
    }

    private var accessibilityText: String {
        let base = "Ant flight outlook: \(label)."
        let queens = band?.winged == true ? " Winged queens are likely." : ""
        return base + queens + " Opens the app."
    }
}

private extension View {
    // iOS 17 requires containerBackground for widgets; earlier versions take a
    // plain background. This keeps one view working from iOS 14 through 17+.
    @ViewBuilder
    func widgetBackgroundCompat(_ color: Color) -> some View {
        if #available(iOSApplicationExtension 17.0, *) {
            containerBackground(for: .widget) { color }
        } else {
            background(color)
        }
    }
}

// MARK: - Widget

struct NuptialWidget: Widget {
    // The kind string must match the iOSName the Flutter side passes to
    // HomeWidget.updateWidget (lib/controller/widgets_mobile.dart).
    let kind: String = "NuptialWidget"

    private var families: [WidgetFamily] {
        if #available(iOSApplicationExtension 16.0, *) {
            return [.systemSmall, .systemMedium,
                    .accessoryCircular, .accessoryRectangular, .accessoryInline]
        }
        return [.systemSmall, .systemMedium]
    }

    var body: some WidgetConfiguration {
        StaticConfiguration(kind: kind, provider: FlightProvider()) { entry in
            NuptialWidgetEntryView(entry: entry)
        }
        .configurationDisplayName("Nuptial Flight")
        .description("Shows today's Ant Flight Index at your location.")
        .supportedFamilies(families)
    }
}

@main
struct NuptialWidgetBundle: WidgetBundle {
    var body: some Widget {
        NuptialWidget()
    }
}
