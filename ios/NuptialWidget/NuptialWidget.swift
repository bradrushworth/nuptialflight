private func dynamic(_ light: UInt32, _ dark: UInt32) -> Color {
    Color(UIColor { trait in
        let v = trait.userInterfaceStyle == .dark ? dark : light
        return UIColor(red: CGFloat((v >> 16) & 0xFF) / 255.0,
                       green: CGFloat((v >> 8) & 0xFF) / 255.0,
                       blue: CGFloat(v & 0xFF) / 255.0,
                       alpha: 1.0)
    })
}

// MARK: - Timeline

struct FlightEntry: TimelineEntry {
    let date: Date
    let bandKey: String
    let label: String
    let odds: String
}

struct FlightProvider: TimelineProvider {
    func placeholder(in context: Context) -> FlightEntry {
        FlightEntry(date: Date(), bandKey: "prime", label: "Prime", odds: "1 in 7")
    }

    func getSnapshot(in context: Context, completion: @escaping (FlightEntry) -> Void) {
        completion(loadEntry())
    }

    func getTimeline(in context: Context, completion: @escaping (Timeline<FlightEntry>) -> Void) {
        // The Flutter app reloads this timeline whenever it saves a new
        // outlook, so the hourly refresh is only a fallback for stale data.
        let next = Calendar.current.date(byAdding: .hour, value: 1, to: Date())
            ?? Date().addingTimeInterval(3600)
        completion(Timeline(entries: [loadEntry()], policy: .after(next)))
    }

    private func loadEntry() -> FlightEntry {
        let store = UserDefaults(suiteName: appGroupId)
        let percentage = store?.integer(forKey: "_percentage") ?? 0
        var key = store?.string(forKey: "_band") ?? ""

        // Band key written by 2.20+; fall back to the old percentage
        // thresholds right after an upgrade so the widget is never blank.
        // Mirrors the same fallback in AppWidgetProvider.kt.
        if key.isEmpty {
            if percentage <= 0 {
                key = ""
            } else if percentage < 50 {
                key = "quiet"
            } else if percentage < 60 {
                key = "watchful"
            } else {
                key = "prime"
            }
        }

        return FlightEntry(date: Date(),
                           bandKey: key,
                           label: store?.string(forKey: "_band_label") ?? "",
                           odds: store?.string(forKey: "_odds") ?? "")
    }
}

